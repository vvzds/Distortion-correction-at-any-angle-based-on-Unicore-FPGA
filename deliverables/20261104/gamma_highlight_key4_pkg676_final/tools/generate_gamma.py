"""Generate compact RGB565 gamma and highlight roll-off lookup tables."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
parts=['// Generated by tools/generate_gamma.py. Gamma exponents 0.60 and 1.60.\n']
for bits in [5,6]:
    for label,gamma in [('bright',0.60),('dark',1.60),('highlight',1.60)]:
        parts.append(f'function [{bits-1}:0] {label}{bits};\n    input [{bits-1}:0] a;\n    begin case(a)\n')
        maximum=(1<<bits)-1
        knee=round(maximum*.75)
        for i in range(1<<bits):
            if label=='highlight':
                z=max(0.,(i-knee)/(maximum-knee))
                j=i if i<=knee else round(knee+(maximum-knee)*z**gamma)
            else:
                j=round(maximum*(i/maximum)**gamma)
            parts.append(f"        {bits}'d{i}: {label}{bits}={bits}'d{j};\n")
        parts.append(f"        default: {label}{bits}=0;\n    endcase end\nendfunction\n")
(ROOT/'source/rtl/gamma_tables.vh').write_text(''.join(parts))
